CREATE OR REPLACE FUNCTION public.link_auth_user_to_profile()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  linked_id bigint;
BEGIN
  IF NEW.email IS NULL OR NEW.email_confirmed_at IS NULL THEN
    RETURN NEW;
  END IF;
  IF EXISTS (SELECT 1 FROM public.profiles WHERE auth_user_id = NEW.id) THEN
    RETURN NEW;
  END IF;

  UPDATE public.profiles
  SET auth_user_id = NEW.id
  WHERE lower(email) = lower(NEW.email)
    AND auth_user_id IS NULL
  RETURNING id INTO linked_id;

  IF linked_id IS NULL THEN
    INSERT INTO public.profiles (auth_user_id, email, full_name, phone, address, role)
    VALUES (
      NEW.id,
      lower(NEW.email),
      COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'full_name', ''), split_part(NEW.email, '@', 1)),
      NULLIF(NEW.raw_user_meta_data ->> 'phone', ''),
      NULLIF(NEW.raw_user_meta_data ->> 'address', ''),
      'resident'
    );
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created_link_profile
  AFTER INSERT OR UPDATE OF email_confirmed_at ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.link_auth_user_to_profile();

CREATE OR REPLACE FUNCTION public.admin_update_profile(
  p_actor_id bigint,
  p_target_id bigint,
  p_fields jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_role text;
  v_target public.profiles;
  v_updated_id bigint;
BEGIN
  LOCK TABLE public.profiles IN SHARE ROW EXCLUSIVE MODE;

  SELECT role INTO v_actor_role
  FROM public.profiles
  WHERE id = p_actor_id AND is_active = true;
  IF v_actor_role IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Administrator access is required' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(p_fields) IS DISTINCT FROM 'object'
     OR p_fields = '{}'::jsonb
     OR (p_fields - ARRAY['full_name', 'phone', 'role', 'is_active']::text[]) <> '{}'::jsonb THEN
    RAISE EXCEPTION 'Invalid profile update fields' USING ERRCODE = '22023';
  END IF;
  IF p_fields ? 'full_name'
     AND (jsonb_typeof(p_fields -> 'full_name') IS DISTINCT FROM 'string'
       OR length(btrim(p_fields ->> 'full_name')) NOT BETWEEN 1 AND 120) THEN
    RAISE EXCEPTION 'Full name must be between 1 and 120 characters' USING ERRCODE = '22023';
  END IF;
  IF p_fields ? 'phone'
     AND (jsonb_typeof(p_fields -> 'phone') NOT IN ('string', 'null')
       OR length(p_fields ->> 'phone') > 40) THEN
    RAISE EXCEPTION 'Phone must be 40 characters or fewer' USING ERRCODE = '22023';
  END IF;
  IF p_fields ? 'role'
     AND (jsonb_typeof(p_fields -> 'role') IS DISTINCT FROM 'string'
       OR p_fields ->> 'role' NOT IN ('resident', 'ldrrmo_staff', 'supervisor', 'admin')) THEN
    RAISE EXCEPTION 'Select a valid role' USING ERRCODE = '22023';
  END IF;
  IF p_fields ? 'is_active'
     AND jsonb_typeof(p_fields -> 'is_active') IS DISTINCT FROM 'boolean' THEN
    RAISE EXCEPTION 'is_active must be a boolean' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_target
  FROM public.profiles
  WHERE id = p_target_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'The user does not exist' USING ERRCODE = 'P0002';
  END IF;
  IF p_target_id = p_actor_id
     AND ((p_fields ? 'is_active' AND p_fields ->> 'is_active' = 'false')
       OR (p_fields ? 'role' AND p_fields ->> 'role' <> 'admin')) THEN
    RAISE EXCEPTION 'You cannot deactivate or demote your own administrator account' USING ERRCODE = '42501';
  END IF;
  IF v_target.role = 'admin' AND v_target.is_active
     AND ((p_fields ? 'role' AND p_fields ->> 'role' <> 'admin')
       OR (p_fields ? 'is_active' AND p_fields ->> 'is_active' = 'false'))
     AND (SELECT count(*) FROM public.profiles WHERE role = 'admin' AND is_active = true) <= 1 THEN
    RAISE EXCEPTION 'The last active administrator cannot be demoted or deactivated' USING ERRCODE = '23514';
  END IF;

  UPDATE public.profiles
  SET full_name = CASE WHEN p_fields ? 'full_name' THEN p_fields ->> 'full_name' ELSE full_name END,
      phone = CASE WHEN p_fields ? 'phone' THEN p_fields ->> 'phone' ELSE phone END,
      role = CASE WHEN p_fields ? 'role' THEN p_fields ->> 'role' ELSE role END,
      is_active = CASE WHEN p_fields ? 'is_active' THEN (p_fields ->> 'is_active')::boolean ELSE is_active END
  WHERE id = p_target_id
  RETURNING id INTO v_updated_id;

  RETURN v_updated_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_emergency_report(
  p_reporter_id bigint,
  p_emergency_type text,
  p_severity text,
  p_description text,
  p_latitude numeric,
  p_longitude numeric,
  p_address_text text,
  p_photo_url text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_report_id bigint;
  v_role text;
  v_title text;
  v_location text;
BEGIN
  SELECT role INTO v_role FROM public.profiles
  WHERE id = p_reporter_id AND is_active = true;
  IF v_role IS DISTINCT FROM 'resident' THEN
    RAISE EXCEPTION 'Only active residents can submit emergency reports' USING ERRCODE = '42501';
  END IF;
  IF (p_latitude IS NULL) <> (p_longitude IS NULL) THEN
    RAISE EXCEPTION 'Provide both coordinates, or leave both empty' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.emergency_reports
    (reporter_id, emergency_type, severity, description, latitude, longitude, address_text, photo_url)
  VALUES
    (p_reporter_id, p_emergency_type, p_severity, p_description, p_latitude, p_longitude, p_address_text, p_photo_url)
  RETURNING id INTO v_report_id;

  INSERT INTO public.audit_logs(user_id, action, table_name, record_id)
  VALUES (p_reporter_id, 'report_created', 'emergency_reports', v_report_id::text);

  v_title := 'New Emergency Report: ' || initcap(replace(p_emergency_type, '_', ' '));
  v_location := CASE
    WHEN p_latitude IS NOT NULL THEN ' at GPS coordinates ' || p_latitude::text || ', ' || p_longitude::text
    WHEN p_address_text IS NOT NULL AND p_address_text <> '' THEN ' for ' || p_address_text
    ELSE ' at an unspecified location'
  END;
  INSERT INTO public.notifications(title, body, channel, status, target_role, sent_at)
  SELECT v_title,
         'A ' || p_severity || ' severity report was submitted' || v_location || '.',
         'in_app', 'sent', roles.role, now()
  FROM (VALUES ('ldrrmo_staff'), ('supervisor'), ('admin')) AS roles(role);

  RETURN v_report_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.transition_emergency_report(
  p_report_id bigint,
  p_actor_id bigint,
  p_status text,
  p_notes text,
  p_after_action_report text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_role text;
  v_old_status text;
  v_reporter_id bigint;
  v_emergency_type text;
  v_after_action_report text;
BEGIN
  SELECT role INTO v_actor_role FROM public.profiles
  WHERE id = p_actor_id AND is_active = true;
  IF v_actor_role IS NULL OR v_actor_role NOT IN ('ldrrmo_staff', 'supervisor', 'admin') THEN
    RAISE EXCEPTION 'Staff access is required' USING ERRCODE = '42501';
  END IF;
  IF p_status IN ('resolved', 'closed') AND v_actor_role NOT IN ('supervisor', 'admin') THEN
    RAISE EXCEPTION 'Supervisor access is required for this status' USING ERRCODE = '42501';
  END IF;
  IF p_after_action_report IS NOT NULL AND v_actor_role NOT IN ('supervisor', 'admin') THEN
    RAISE EXCEPTION 'Supervisor access is required to edit the after-action report' USING ERRCODE = '42501';
  END IF;

  SELECT status, reporter_id, emergency_type, after_action_report
  INTO v_old_status, v_reporter_id, v_emergency_type, v_after_action_report
  FROM public.emergency_reports WHERE id = p_report_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'The report does not exist' USING ERRCODE = 'P0002';
  END IF;
  IF p_status = 'closed'
     AND COALESCE(NULLIF(p_after_action_report, ''), v_after_action_report) IS NULL THEN
    RAISE EXCEPTION 'An after-action report is required before closing an incident' USING ERRCODE = '22023';
  END IF;

  UPDATE public.emergency_reports
  SET status = p_status,
      after_action_report = COALESCE(NULLIF(p_after_action_report, ''), after_action_report)
  WHERE id = p_report_id;

  IF v_old_status IS DISTINCT FROM p_status THEN
    IF p_status IN ('resolved', 'closed') THEN
      UPDATE public.safe_routes SET is_active = false
      WHERE report_id = p_report_id AND is_active = true;
    END IF;
    INSERT INTO public.status_updates(report_id, updated_by, old_status, new_status, notes)
    VALUES (p_report_id, p_actor_id, v_old_status, p_status, p_notes);
    INSERT INTO public.notifications(title, body, channel, status, target_user_id, sent_by, sent_at)
    VALUES (
      'Report status updated',
      'Your ' || replace(v_emergency_type, '_', ' ') || ' report status is now ' || replace(p_status, '_', ' ') || '.',
      'in_app', 'sent', v_reporter_id, p_actor_id, now()
    );
    INSERT INTO public.audit_logs(user_id, action, table_name, record_id, old_values, new_values)
    VALUES (
      p_actor_id, 'report_status_changed', 'emergency_reports', p_report_id::text,
      jsonb_build_object('status', v_old_status), jsonb_build_object('status', p_status)
    );
  END IF;
  RETURN p_report_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.assign_emergency_report(
  p_report_id bigint,
  p_responder_id bigint,
  p_actor_id bigint,
  p_notes text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_role text;
  v_responder_role text;
  v_old_status text;
  v_new_status text;
  v_assignment_id bigint;
BEGIN
  SELECT role INTO v_actor_role FROM public.profiles
  WHERE id = p_actor_id AND is_active = true;
  IF v_actor_role IS NULL OR v_actor_role NOT IN ('supervisor', 'admin') THEN
    RAISE EXCEPTION 'Supervisor access is required' USING ERRCODE = '42501';
  END IF;
  SELECT role INTO v_responder_role FROM public.profiles
  WHERE id = p_responder_id AND is_active = true;
  IF v_responder_role IS NULL OR v_responder_role NOT IN ('ldrrmo_staff', 'supervisor', 'admin') THEN
    RAISE EXCEPTION 'Choose an active staff responder' USING ERRCODE = '22023';
  END IF;

  SELECT status INTO v_old_status FROM public.emergency_reports
  WHERE id = p_report_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'The report does not exist' USING ERRCODE = 'P0002';
  END IF;
  INSERT INTO public.report_assignments(report_id, responder_id, assigned_by, notes)
  VALUES (p_report_id, p_responder_id, p_actor_id, p_notes)
  RETURNING id INTO v_assignment_id;

  v_new_status := CASE WHEN v_old_status = 'open' THEN 'in_progress' ELSE v_old_status END;
  UPDATE public.emergency_reports
  SET assigned_to = p_responder_id, status = v_new_status
  WHERE id = p_report_id;
  IF v_new_status IS DISTINCT FROM v_old_status THEN
    INSERT INTO public.status_updates(report_id, updated_by, old_status, new_status, notes)
    VALUES (p_report_id, p_actor_id, v_old_status, v_new_status, 'Responder assigned');
  END IF;
  INSERT INTO public.notifications(title, body, channel, status, target_user_id, sent_by, sent_at)
  VALUES (
    'Incident assignment', 'You have been assigned to an emergency response.',
    'in_app', 'sent', p_responder_id, p_actor_id, now()
  );
  INSERT INTO public.audit_logs(user_id, action, table_name, record_id, new_values)
  VALUES (p_actor_id, 'responder_assigned', 'emergency_reports', p_report_id::text,
          jsonb_build_object('responder_id', p_responder_id));
  RETURN v_assignment_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.publish_safe_route(
  p_report_id bigint,
  p_actor_id bigint,
  p_title text,
  p_path jsonb
)
RETURNS SETOF public.safe_routes
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_role text;
  v_emergency_type text;
  v_status text;
  v_route public.safe_routes;
BEGIN
  SELECT role INTO v_actor_role FROM public.profiles
  WHERE id = p_actor_id AND is_active = true;
  IF v_actor_role IS NULL OR v_actor_role NOT IN ('supervisor', 'admin') THEN
    RAISE EXCEPTION 'Supervisor access is required' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(p_path) <> 'array' OR jsonb_array_length(p_path) NOT BETWEEN 2 AND 100 THEN
    RAISE EXCEPTION 'A route must contain between 2 and 100 map points' USING ERRCODE = '22023';
  END IF;
  SELECT emergency_type, status INTO v_emergency_type, v_status
  FROM public.emergency_reports WHERE id = p_report_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'The report does not exist' USING ERRCODE = 'P0002';
  END IF;
  IF v_emergency_type <> 'landslide' OR v_status IN ('resolved', 'closed') THEN
    RAISE EXCEPTION 'Routes may only be published for active landslide reports' USING ERRCODE = '22023';
  END IF;

  UPDATE public.safe_routes SET is_active = false
  WHERE report_id = p_report_id AND is_active = true;
  INSERT INTO public.safe_routes(report_id, title, path_json, created_by)
  VALUES (p_report_id, p_title, p_path, p_actor_id)
  RETURNING * INTO v_route;
  INSERT INTO public.audit_logs(user_id, action, table_name, record_id, new_values)
  VALUES (p_actor_id, 'safe_route_published', 'safe_routes', v_route.id::text,
          jsonb_build_object('report_id', p_report_id));
  RETURN NEXT v_route;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_sensor_reading(
  p_device_id bigint,
  p_reading numeric
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_device public.iot_devices;
  v_alert boolean;
BEGIN
  SELECT * INTO v_device FROM public.iot_devices
  WHERE id = p_device_id AND status = 'active' FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'The device is inactive or does not exist' USING ERRCODE = 'P0002';
  END IF;
  v_alert := p_reading >= v_device.alert_threshold;
  INSERT INTO public.sensor_readings(device_id, value, unit, is_alert)
  VALUES (v_device.id, p_reading, v_device.alert_unit, v_alert);
  UPDATE public.iot_devices
  SET last_reading = p_reading, last_reading_at = now()
  WHERE id = v_device.id;
  IF v_alert THEN
    INSERT INTO public.notifications(title, body, channel, status, target_role, sent_at)
    SELECT 'Sensor Alert: ' || v_device.name,
           'Measured ' || p_reading::text || ' ' || v_device.alert_unit
             || '; configured threshold is ' || v_device.alert_threshold::text
             || ' ' || v_device.alert_unit || '.',
           'in_app', 'sent', roles.role, now()
    FROM (VALUES ('ldrrmo_staff'), ('supervisor'), ('admin')) AS roles(role);
  END IF;
  RETURN jsonb_build_object('accepted', true, 'is_alert', v_alert);
END;
$$;

